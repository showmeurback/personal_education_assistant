# ── DOCX с рисунками (для тестов агента описания изображений) ────────────────
import io  # noqa: E402
import zipfile  # noqa: E402


def png(w: int, h: int, color: str = "navy", text: str | None = None) -> bytes:
    from PIL import Image, ImageDraw

    im = Image.new("RGB", (w, h), color)
    if text:
        draw = ImageDraw.Draw(im)
        for i, line in enumerate(text.split("\n")):
            draw.text((20, 20 + 24 * i), line, fill="black")
    buf = io.BytesIO()
    im.save(buf, "PNG")
    return buf.getvalue()


W = 'xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"'
A = 'xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"'
R = 'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'


def make_docx(paragraphs: list[str | tuple[str, str]], media: dict[str, bytes]) -> bytes:
    """paragraphs: строка — абзац текста, ("img", rId) — абзац с рисунком."""
    body = []
    for p in paragraphs:
        if isinstance(p, tuple):
            body.append(f'<w:p><w:r><w:drawing><a:blip r:embed="{p[1]}"/></w:drawing></w:r></w:p>')
        else:
            body.append(f"<w:p><w:r><w:t>{p}</w:t></w:r></w:p>")
    doc = f'<?xml version="1.0"?><w:document {W} {A} {R}><w:body>{"".join(body)}</w:body></w:document>'
    rels = "".join(f'<Relationship Id="rId{i}" Target="media/{name}" Type="image"/>'
                   for i, name in enumerate(media, start=1))
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("word/document.xml", doc)
        zf.writestr("word/_rels/document.xml.rels",
                    f'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">{rels}</Relationships>')
        for name, blob in media.items():
            zf.writestr(f"word/media/{name}", blob)
    return buf.getvalue()



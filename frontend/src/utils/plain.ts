/*
 * Понятные названия шагов проверки для преподавателей любых дисциплин.
 * Протокол на сервере хранит технические названия (они нужны для отладки и описаны
 * в документации); интерфейс показывает простое название и одно предложение о том,
 * что делает шаг, а техническое название — в подробностях шага.
 */
import type { ProtocolStep } from "@/api";

export interface PlainStep { title: string; text: string }

const BY_ORDER: Record<string, PlainStep> = {
  "1": { title: "Подготовка текста", text: "Слова отчёта приводятся к начальной форме, чтобы их можно было сравнивать с заданием и другими отчётами." },
  "2": { title: "Формальные требования", text: "Проверка по правилам, которые задал преподаватель: объём, обязательные разделы, язык и связь с темой задания." },
  "3": { title: "Поиск списывания", text: "Отчёт сравнивается с отчётами других студентов по этой же работе. Почти полное совпадение означает списывание — такой отчёт отклоняется сразу." },
  "3.5": { title: "Соответствие этой работе", text: "Смысл отчёта сравнивается с заданием этой и других работ курса. Если отчёт больше похож на другую работу, решение остаётся за преподавателем." },
  "4": { title: "Описание рисунков", text: "Искусственный интеллект описывает словами скриншоты, графики, фотографии и схемы, чтобы следующие шаги учли и их." },
  "8": { title: "Итоговое решение", text: "Мнения проверяющих сводятся по заранее заданным правилам. Если они согласны и уверены, решение принимается автоматически, иначе отчёт передаётся преподавателю." },
  "9": { title: "Пояснение для студента", text: "Искусственный интеллект кратко пишет студенту, что нужно исправить." },
};

const JUDGE_TEXT = "Искусственный интеллект читает отчёт и решает, выполнено ли задание. Три проверяющих с разной строгостью работают как комиссия; каждый указывает, какие пункты задания выполнены.";

export function plainStep(step: ProtocolStep): PlainStep {
  if (step.kind === "neural" && /оценщик/i.test(step.title)) {
    return { title: step.title.replace(/оценщик/i, "проверяющий"), text: JUDGE_TEXT };
  }
  return BY_ORDER[String(step.order)] ?? { title: step.title, text: "" };
}

export const KIND_LABEL = { symbolic: "Проверка по правилам", neural: "Искусственный интеллект" } as const;
